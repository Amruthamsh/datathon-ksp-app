def _ok(value):
    return {"value": value, "todo": None}


def _todo(text):
    return {"value": None, "todo": text}


def _d(s):
    return (s or "")[:10] or None


def build_final_report(case_id: int) -> dict | None:
    with get_connection() as conn:
        case = conn.execute(
            """
            SELECT cm.CaseMasterID, cm.CrimeNo, cm.CrimeRegisteredDate, cm.IncidentFromDate,
                   cm.IncidentToDate, cm.BriefFacts, cm.CaseStatusID, cm.PoliceStationID,
                   csh.CrimeHeadName AS crime, cs.CaseStatusName AS status,
                   u.UnitName AS station, d.DistrictName AS district,
                   e.FirstName AS io_name, r.RankName AS io_rank, r.Hierarchy AS io_hierarchy,
                   c.CourtName AS court
            FROM CaseMaster cm
            JOIN CrimeSubHead csh ON csh.CrimeSubHeadID = cm.CrimeMinorHeadID
            LEFT JOIN CaseStatusMaster cs ON cs.CaseStatusID = cm.CaseStatusID
            LEFT JOIN Unit u ON u.UnitID = cm.PoliceStationID
            LEFT JOIN District d ON d.DistrictID = u.DistrictID
            LEFT JOIN Employee e ON e.EmployeeID = cm.PolicePersonID
            LEFT JOIN Rank r ON r.RankID = e.RankID
            LEFT JOIN Court c ON c.CourtID = cm.CourtID
            WHERE cm.CaseMasterID = ?
            """,
            [case_id],
        ).fetchone()
        if not case:
            return None
        case = dict(case)

        accused = [dict(r) for r in conn.execute(
            """
            SELECT a.AccusedMasterID, a.AccusedName AS name, a.AgeYear AS age, a.GenderID AS gender,
                   a.PersonID AS label,
                   (SELECT MIN(ars.ArrestSurrenderDate) FROM ArrestSurrender ars
                     WHERE ars.AccusedMasterID = a.AccusedMasterID AND ars.CaseMasterID = a.CaseMasterID) AS arrested,
                   (SELECT COUNT(DISTINCT a2.CaseMasterID) FROM Accused a2
                     WHERE a2.AccusedName = a.AccusedName AND a2.CaseMasterID <> a.CaseMasterID) AS other_firs
            FROM Accused a WHERE a.CaseMasterID = ?
            ORDER BY a.PersonID
            """,
            [case_id],
        )]
        complainant = conn.execute(
            "SELECT ComplainantName AS name, AgeYear AS age, GenderID AS gender FROM ComplainantDetails WHERE CaseMasterID = ?",
            [case_id],
        ).fetchone()
        victims = [dict(r) for r in conn.execute(
            "SELECT VictimName AS name, AgeYear AS age, GenderID AS gender FROM Victim WHERE CaseMasterID = ?",
            [case_id],
        )]
        recorded = [dict(r) for r in conn.execute(
            "SELECT ActID AS act, SectionID AS section FROM ActSectionAssociation WHERE CaseMasterID = ? ORDER BY ActOrderID",
            [case_id],
        )]
        chargesheet_filed = conn.execute(
            "SELECT MIN(csdate) FROM ChargesheetDetails WHERE CaseMasterID = ?", [case_id]
        ).fetchone()[0]

    as_of = bnss.data_as_of()
    offence_date = _d(case["IncidentFromDate"]) or _d(case["CrimeRegisteredDate"])
    fir_date = _d(case["CrimeRegisteredDate"])
    substantive = "IPC" if offence_date and offence_date < REFORM_DATE else "BNS"
    procedure = "CrPC" if fir_date and fir_date < REFORM_DATE else "BNSS"
    report_section = "s.173 CrPC" if procedure == "CrPC" else "s.193 BNSS"
    statement_section = "s.161 CrPC" if procedure == "CrPC" else "s.180 BNSS"
    evidence_act = "s.65B Indian Evidence Act" if procedure == "CrPC" else "s.63 Bharatiya Sakshya Adhiniyam"
    notice_section = "s.41A CrPC" if procedure == "CrPC" else "s.35 BNSS"

    o = OFFENCES.get(case["crime"])
    flags = []
    charges = []
    if o:
        for sec, title in o["bns" if substantive == "BNS" else "ipc"]:
            charges.append({"act": substantive, "section": sec, "title": title})
        for act, sec, title in o.get("special", []):
            charges.append({"act": act, "section": sec, "title": title})
        if o.get("confirm"):
            flags.append({"level": "confirm", "text": o["confirm"]})
    else:
        flags.append({"level": "todo", "text": f"No charge mapping for offence type '{case['crime']}' — IO to frame sections."})

    # A child victim of a sexual offence brings in POCSO (penetrative assault, s.4).
    child_victim = any(v["age"] is not None and v["age"] < 18 for v in victims)
    if case["crime"] == "Sexual Assault" and child_victim:
        charges.append({"act": "POCSO", "section": "4", "title": "Penetrative sexual assault on a child"})

    charged_sections = {(c["act"], c["section"].split("(")[0]) for c in charges}
    recorded_out = []
    for r in recorded:
        act = "BNS" if r["act"] == "BNS" else r["act"]
        consistent = (act, str(r["section"]).split("(")[0]) in charged_sections or (
            act == "IPC" and substantive == "IPC" and (act, str(r["section"])) in charged_sections
        )
        recorded_out.append({**r, "consistent": consistent})
    stray = [r for r in recorded_out if not r["consistent"]]
    if stray:
        flags.append({
            "level": "flag",
            "text": "Sections recorded in the FIR data are not supported by the offence ("
            + ", ".join(f"{r['act']} {r['section']}" for r in stray)
            + f" on a {case['crime'].lower()} case). Remove them or record the facts that justify them before filing.",
        })

    adults = [a for a in accused if a["age"] is None or a["age"] >= bnss.ADULT_AGE]
    children = [a for a in accused if a["age"] is not None and a["age"] < bnss.ADULT_AGE]

    clocks = {c["AccusedMasterID"]: c for c in bnss.get_case_clocks(case_id) if c["rule"] == "default_bail"}
    accused_out = []
    for a in adults:
        clock = clocks.get(a["AccusedMasterID"])
        accused_out.append({
            "label": a["label"],
            "name": a["name"],
            "age": a["age"],
            "gender": a["gender"],
            "parent": _todo("Father's / husband's name"),
            "address": _todo("Residential address"),
            "arrest": _ok(_d(a["arrested"])) if a["arrested"] else _todo(f"Not arrested — record whether absconding, served notice ({notice_section}) or on anticipatory bail"),
            "custody": _todo("Custody / bail status and date of release, if any") if a["arrested"] else _ok("Not in custody"),
            "default_bail": {"days_left": clock["days_left"], "deadline": clock["deadline"], "band": clock["band"]} if clock else None,
            "other_firs": a["other_firs"],
        })
        if not a["arrested"]:
            flags.append({"level": "todo", "text": f"{a['label']} {a['name']} is not arrested — state the reason and seek a warrant/proclamation if absconding."})

    for a in children:
        flags.append({
            "level": "flag",
            "text": f"{a['label']} {a['name']} is {a['age']} — a child in conflict with law. Do not charge-sheet with the adults: "
            "submit a separate report to the Juvenile Justice Board (JJ Act 2015; s.23 bars joint proceedings).",
        })

    if case["io_hierarchy"] and case["io_hierarchy"] >= 10:
        flags.append({
            "level": "flag",
            "text": f"Investigating officer is recorded as {case['io_rank']}. Investigation is normally conducted by a Sub-Inspector or above — confirm the IO before filing.",
        })

    if case["CaseStatusID"] != 1 or chargesheet_filed:
        flags.insert(0, {
            "level": "flag",
            "text": f"A final report already appears to be on record ({_d(chargesheet_filed) or case['status']}). This draft is for reference only.",
        })

    witnesses = []
    if complainant:
        witnesses.append({"label": "CW1", "name": complainant["name"], "role": "Complainant / informant", "proves": _ok("Lodging of the complaint and the facts reported")})
    for v in victims:
        witnesses.append({"label": f"CW{len(witnesses) + 1}", "name": v["name"], "role": "Victim", "proves": _todo(f"What {v['name']} saw / lost — from the {statement_section} statement")})
    witnesses.append({"label": f"CW{len(witnesses) + 1}", "name": None, "role": "Panch / mahazar witnesses", "proves": _todo("Names and what each mahazar proves")})
    witnesses.append({"label": f"CW{len(witnesses) + 1}", "name": case["io_name"], "role": "Investigating officer", "proves": _ok("Course of investigation, arrests, seizures")})

    documents = [
        {"name": f"FIR No. {case['CrimeNo']} dated {fir_date}", "status": "on_record"},
        {"name": f"Complaint of {complainant['name']}" if complainant else "Complaint", "status": "on_record" if complainant else "todo"},
    ]
    for a in adults:
        if a["arrested"]:
            documents.append({"name": f"Arrest memo — {a['label']} {a['name']} ({_d(a['arrested'])})", "status": "on_record"})
    documents.append({"name": f"Witness statements under {statement_section}", "status": "todo"})
    for doc in EVIDENCE.get(case["crime"], []):
        documents.append({"name": doc.replace("BSA s.63", evidence_act).replace("BNSS s.184", "s.184 BNSS" if procedure == "BNSS" else "s.164A CrPC").replace("BNSS s.183", "s.183 BNSS" if procedure == "BNSS" else "s.164 CrPC"), "status": "todo"})

    is_sexual = case["crime"] == "Sexual Assault"
    is_cyber = case["crime"] == "Cybercrime / Online Fraud"
    disclosures = [
        {"item": "Names of the parties", "field": _ok(f"{len(adults)} accused charged, complainant {complainant['name'] if complainant else '—'}, {len(victims)} victim(s)")},
        {"item": "Nature of the information", "field": _ok(case["BriefFacts"]) if case["BriefFacts"] else _todo("Nature of the information received")},
        {"item": "Persons acquainted with the circumstances", "field": _ok(f"{len(witnesses)} witnesses listed (CW1–CW{len(witnesses)})")},
        {"item": "Whether an offence appears to have been committed, and by whom", "field": _ok(f"{', '.join(c['act'] + ' ' + c['section'] for c in charges) or '—'} — by {', '.join(a['label'] for a in adults) or '—'}")},
        {"item": "Whether the accused has been arrested", "field": _ok("; ".join(f"{a['label']}: {'arrested ' + _d(a['arrested']) if a['arrested'] else 'not arrested'}" for a in adults) or "—")},
        {"item": "Whether released on bond, and with or without sureties", "field": _todo("Bail / bond details for each arrested accused")},
        {"item": "Whether forwarded in custody", "field": _todo("Custody status for each arrested accused")},
        {"item": "Medical examination report of the woman (sexual offences)", "field": _todo("Attach the medical report") if is_sexual else _ok("Not applicable")},
        {"item": "Sequence of custody of electronic devices", "field": _todo("Chain-of-custody record for seized devices") if is_cyber else _ok("Not applicable")},
    ]

    victim_clock = next((c for c in bnss.get_case_clocks(case_id) if c["rule"] == "victim_update"), None)

    narrative = (
        f"On {offence_date or '[date of offence]'}, within the limits of {case['station']}, {case['district']} district, "
        f"{complainant['name'] if complainant else 'the complainant'} reported that: {case['BriefFacts'] or '[facts]'} "
        f"FIR No. {case['CrimeNo']} was registered on {fir_date} for {case['crime'].lower()}. "
        + (
            "During investigation, " + "; ".join(f"{a['label']} {a['name']} was arrested on {_d(a['arrested'])}" for a in adults if a["arrested"]) + "."
            if any(a["arrested"] for a in adults) else "No accused has been arrested so far."
        )
    )

    todo_count = sum(1 for a in accused_out for k in ("parent", "address", "arrest", "custody") if a[k]["todo"])
    todo_count += sum(1 for w in witnesses if w["proves"]["todo"])
    todo_count += sum(1 for d in documents if d["status"] == "todo")
    todo_count += sum(1 for x in disclosures if x["field"]["todo"])

    return {
        "as_of": as_of,
        "law": {"substantive": substantive, "procedure": procedure, "report_section": report_section,
                "note": None if substantive == "BNS" else f"Offence before {REFORM_DATE}: charged under the IPC."},
        "header": {
            "district": case["district"],
            "station": case["station"],
            "fir_no": case["CrimeNo"],
            "fir_date": fir_date,
            "offence_date": offence_date,
            "report_no": _todo("Final report number"),
            "report_date": _todo("Date of submission"),
            "report_type": "Charge sheet",
            "court": _ok(case["court"]) if case["court"] else _todo("Jurisdictional Magistrate"),
            "io": {"name": case["io_name"], "rank": case["io_rank"]},
        },
        "offence": {
            "type": case["crime"],
            "charges": charges,
            "punishment": o["punishment"] if o else None,
            "cognizable": o["cognizable"] if o else None,
            "bailable": o["bailable"] if o else None,
            "recorded_sections": recorded_out,
        },
        "complainant": complainant and dict(complainant),
        "victims": victims,
        "accused": accused_out,
        "juveniles": [{"label": a["label"], "name": a["name"], "age": a["age"]} for a in children],
        "witnesses": witnesses,
        "documents": documents,
        "disclosures": disclosures,
        "victim_update": victim_clock and {"deadline": victim_clock["deadline"], "days_left": victim_clock["days_left"]},
        "narrative": {"value": narrative, "todo": "Expand with the evidence collected and what each witness establishes"},
        "flags": flags,
        "todo_count": todo_count,
        "generated_on": date.today().isoformat(),
    }
