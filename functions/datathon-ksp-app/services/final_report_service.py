"""Final Report (chargesheet) draft — BNSS s.193 / CrPC s.173.

Deterministic: every field comes from the case records, or is returned as an
explicit IO task. Nothing is generated by a language model, so the draft can
never present an invented fact as a record. The charge is derived from the
offence type, not the FIR's act/section tags (which are unreliable in the
synthetic corpus) — mismatching tags are surfaced as flags for the IO.

Field shape: {"value": ..., "todo": None} for data, {"value": None,
"todo": "<what the IO must supply>"} for gaps.
"""

